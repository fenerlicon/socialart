import pkg from 'pg';
const { Client } = pkg;
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const envPath = path.resolve(__dirname, '../.env');
const envFile = fs.readFileSync(envPath, 'utf8');

const envConfig = {};
envFile.split('\n').forEach(line => {
  const match = line.match(/^([^=]+)=(.*)$/);
  if (match) {
    envConfig[match[1]] = match[2].trim();
  }
});

const DB_PASSWORD = envConfig['SUPABASE_DB_PASSWORD'];
const SUPABASE_PROJECT_ID = envConfig['VITE_SUPABASE_URL']?.split('//')[1]?.split('.')[0];
const connectionString = `postgresql://postgres:${encodeURIComponent(DB_PASSWORD)}@db.${SUPABASE_PROJECT_ID}.supabase.co:5432/postgres`;

async function fixAppointments() {
  const client = new Client({ connectionString });
  try {
    await client.connect();
    
    const maxRes = await client.query('SELECT COALESCE(MAX(id), 0) as max_id FROM appointments;');
    const maxId = parseInt(maxRes.rows[0].max_id);
    const nextVal = maxId > 0 ? maxId + 1 : 1;
    console.log(`Max ID is ${maxId}, setting sequence to start with ${nextVal}`);
    
    // Check if it already has an identity
    const identityCheck = await client.query(`
      SELECT identity_generation 
      FROM information_schema.columns 
      WHERE table_name = 'appointments' AND column_name = 'id';
    `);
    
    if (identityCheck.rows[0].identity_generation === null) {
      console.log('Adding IDENTITY constraint...');
      await client.query(`ALTER TABLE appointments ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH ${nextVal});`);
      console.log('Identity added successfully.');
    } else {
      console.log('Identity already exists. Updating sequence...');
      await client.query(`ALTER TABLE appointments ALTER COLUMN id RESTART WITH ${nextVal};`);
      console.log('Sequence updated.');
    }
  } catch (err) {
    console.error('Error fixing appointments table:', err);
  } finally {
    await client.end();
  }
}

fixAppointments();
